export const FISH_SPECIES = Object.fromEntries(FISHING_SPECIES.map(fish => [fish.id, fish]));
export const FISH_BY_RARITY = [0, 1, 2, 3, 4].map(rarity => FISHING_SPECIES.filter(fish => fish.rarity === rarity));

// Preserve the original tier odds independently of the number of fish in a tier.
export const FISH_POOLS = {
  white: [{ rarity: 0, weight: 1 }],
  green: [{ rarity: 0, weight: 2 }, { rarity: 1, weight: 1 }],
  orange: [{ rarity: 2, weight: 1 }, { rarity: 3, weight: 1 }],
  red: [{ rarity: 3, weight: 1 }, { rarity: 4, weight: 1 }],
};

export function chooseFishingSpecies(band, rarityBoost = 0, random = Math.random) {
  const tiers = FISH_POOLS[band];
  const weights = tiers.map(tier => tier.weight * (1 + tier.rarity * rarityBoost));
  let roll = random() * weights.reduce((sum, weight) => sum + weight, 0);
  let rarity = tiers[tiers.length - 1].rarity;
  for (let index = 0; index < tiers.length; index += 1) {
    roll -= weights[index];
    if (roll < 0) { rarity = tiers[index].rarity; break; }
  }
  const fish = FISH_BY_RARITY[rarity];
  return fish[Math.min(fish.length - 1, Math.floor(random() * fish.length))];
}

